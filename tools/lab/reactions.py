#!/usr/bin/env python3
"""Write lib/models/style_quiet.dart from the wave-7 lab runs.

    tools/lab/reactions.py [--threshold 0.15] [--runs 'build/lab/w7-*']

Reads every txt2img run without a sweep (7b/7c/7d, 7f-*, sc-*, fm-*, cal-*),
averages each cell's `reaction` (histogram distance from the model's own
style-less baseline, metrics.go) over the subjects, and lists the (model, style)
pairs under the threshold: the model painted the same picture with the block
as without it. That is the only verdict the colour metric can give — a high
number means the picture changed, not that the style arrived (Illustrious
scores 0.85 by dissolving the figure into scribbles) — so the file carries
"quiet" pairs only and the picker dims them instead of hiding them. Styles and
models that are not in the registries are dropped; a pair that was never
measured is simply absent, which the app reads as "unknown", never as quiet.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import re
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "lib/models/style_quiet.dart"


def ids(pattern: str) -> set[str]:
    found: set[str] = set()
    for f in glob.glob(str(ROOT / pattern)):
        found |= set(re.findall(r"^    id: '([^']+)',", Path(f).read_text(), re.M))
    return found


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--threshold", type=float, default=0.15)
    ap.add_argument("--runs", default="build/lab/w7-*")
    args = ap.parse_args()

    styles = ids("lib/models/style_presets_*.dart")
    models = ids("lib/models/image_model.dart")
    agg: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    runs: list[str] = []
    for d in sorted(glob.glob(str(ROOT / args.runs))):
        spec, metrics = Path(d, "spec.json"), Path(d, "metrics.json")
        if not spec.is_file() or not metrics.is_file():
            continue
        s = json.loads(spec.read_text())
        if s.get("sweep") or s.get("flows") != ["txt2img"]:
            continue
        name = os.path.basename(d)
        if name.startswith(("w7-7a", "w7-7e", "w7-7h")):  # escaping / position / tag ablations
            continue
        runs.append(name)
        for key, cell in json.loads(metrics.read_text())["cells"].items():
            if "reaction" not in cell:
                continue
            _flow, model, style, _prompt = key.split("__")
            if model in models and style in styles:
                agg[model][style].append(cell["reaction"])

    quiet: dict[str, list[str]] = {}
    pairs = 0
    for model in sorted(agg):
        low = sorted(s for s, v in agg[model].items() if statistics.mean(v) < args.threshold)
        if low:
            quiet[model] = low
            pairs += len(low)
    measured = sum(len(v) for v in agg.values())

    lines = [
        "// GENERATED by tools/lab/reactions.py from the wave-7 lab runs. Do not edit by hand.",
        f"// {len(runs)} runs, {measured} (model, style) pairs measured, {pairs} quiet "
        f"(mean reaction < {args.threshold}).",
        "",
        "/// Pairs where the model painted the same picture with the style block as",
        "/// without it (colour histogram distance from its own baseline under",
        f"/// {args.threshold}, averaged over the subjects). The metric sees colour only, so",
        "/// this is the one verdict it can give; a style missing here was either not",
        "/// measured on that model or changed the picture — not necessarily for the",
        "/// better.",
        f"const kStyleQuietThreshold = {args.threshold};",
        "",
        "const kStyleQuietOn = <String, Set<String>>{",
    ]
    for model, low in quiet.items():
        lines.append(f"  '{model}': {{")
        lines.extend(f"    '{s}'," for s in low)
        lines.append("  },")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(runs)} runs, {measured} measured, {pairs} quiet on {len(quiet)} models")


if __name__ == "__main__":
    main()
